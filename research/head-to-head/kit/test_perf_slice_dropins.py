"""Check exact perf.slice drop-in snapshots, restores, and audits."""

from __future__ import annotations

import base64
import json
import os
import stat
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


HELPER = Path(__file__).parent / "lib/perf_slice_dropins.py"


class PerfSliceDropinsTest(unittest.TestCase):
    """Exercise the real drop-in helper against isolated files and paths."""

    def run_helper(self, *arguments: str) -> subprocess.CompletedProcess[str]:
        """Run the helper's public command interface without host systemd state."""
        return subprocess.run(
            [sys.executable, "-I", str(HELPER), *arguments],
            capture_output=True,
            text=True,
            check=False,
        )

    def snapshot(
        self,
        root: Path,
        dropin_paths: list[Path],
        allowed_cpus: str,
    ) -> tuple[Path, Path, subprocess.CompletedProcess[str]]:
        """Capture a baseline into JSON and raw file copies."""
        output = root / "baseline.json"
        raw = root / "baseline-files"
        result = self.run_helper(
            "snapshot",
            "--drop-in-paths",
            " ".join(map(str, dropin_paths)),
            "--allowed-cpus",
            allowed_cpus,
            "--output",
            str(output),
            "--raw-dir",
            str(raw),
        )
        return output, raw, result

    def test_snapshot_keeps_exact_path_content_and_allowed_cpus(self) -> None:
        """The baseline records original bytes and the systemd AllowedCPUs value."""
        with tempfile.TemporaryDirectory(prefix="j317-perf-slice-capture-") as temporary:
            root = Path(temporary)
            dropin = root / "perf.slice.d/50-AllowedCPUs.conf"
            dropin.parent.mkdir()
            content = (
                b'# generated by systemctl set-property\n'
                b"[Slice]\nAllowedCPUs=\nAllowedCPUs=1-3\n"
            )
            dropin.write_bytes(content)

            output, raw, result = self.snapshot(root, [dropin], "1-3")

            self.assertEqual(result.returncode, 0, result.stderr)
            snapshot = json.loads(output.read_text())
            self.assertEqual(snapshot["drop_in_paths"], [str(dropin)])
            self.assertEqual(snapshot["allowed_cpus"], "1-3")
            self.assertEqual(
                base64.b64decode(snapshot["files"][0]["content_base64"]), content
            )
            self.assertEqual(Path(snapshot["files"][0]["artifact_path"]).read_bytes(), content)
            self.assertEqual(list(raw.iterdir()), [Path(snapshot["files"][0]["artifact_path"])])

    def test_restore_reinstates_exact_bytes_and_removes_hold_created_dropins(self) -> None:
        """A hold restores the saved file byte-for-byte and removes its new override."""
        with tempfile.TemporaryDirectory(prefix="j317-perf-slice-restore-") as temporary:
            root = Path(temporary)
            control_dir = root / "system.control/perf.slice.d"
            baseline = control_dir / "50-AllowedCPUs.conf"
            baseline.parent.mkdir(parents=True)
            original = b"[Slice]\nAllowedCPUs=\nAllowedCPUs=1-3\n"
            baseline.write_bytes(original)
            baseline.chmod(0o640)
            original_mtime_ns = 1_791_328_000_123_456_789
            os.utime(baseline, ns=(original_mtime_ns, original_mtime_ns))
            original_stat = baseline.stat()
            memory_dropin = control_dir / "50-MemoryMax.conf"
            memory_original = b"[Slice]\nMemoryMax=6442450944\n"
            memory_dropin.write_bytes(memory_original)
            snapshot_path, _, capture = self.snapshot(
                root, [baseline, memory_dropin], "1-3"
            )
            self.assertEqual(capture.returncode, 0, capture.stderr)

            baseline.write_bytes(b"[Slice]\nAllowedCPUs=0-5\n")
            memory_dropin.write_bytes(b"[Slice]\nMemoryMax=8589934592\n")
            generated = control_dir / "60-extra.conf"
            generated.write_bytes(b"[Slice]\nAllowedCPUs=0-5\n")
            restore = self.run_helper(
                "restore",
                "--baseline",
                str(snapshot_path),
                "--current-drop-in-paths",
                f"{baseline} {memory_dropin} {generated}",
                "--control-dir",
                str(control_dir),
            )

            self.assertEqual(restore.returncode, 0, restore.stderr)
            self.assertEqual(baseline.read_bytes(), original)
            self.assertEqual(memory_dropin.read_bytes(), memory_original)
            restored_stat = baseline.stat()
            self.assertEqual(stat.S_IMODE(restored_stat.st_mode), 0o640)
            self.assertEqual(restored_stat.st_uid, original_stat.st_uid)
            self.assertEqual(restored_stat.st_gid, original_stat.st_gid)
            self.assertEqual(restored_stat.st_mtime_ns, original_mtime_ns)
            self.assertFalse(generated.exists())
            verify = self.run_helper(
                "verify",
                "--baseline",
                str(snapshot_path),
                "--drop-in-paths",
                f"{baseline} {memory_dropin}",
                "--allowed-cpus",
                "1-3",
            )
            self.assertEqual(verify.returncode, 0, verify.stderr)

    def test_absent_runtime_dropin_is_restored_without_touching_static_dropins(self) -> None:
        """An absent control drop-in is removed while unrelated unit files stay intact."""
        with tempfile.TemporaryDirectory(prefix="j317-perf-slice-absent-") as temporary:
            root = Path(temporary)
            control_dir = root / "system.control/perf.slice.d"
            control_dir.mkdir(parents=True)
            static_dropin = root / "etc/perf.slice.d/20-local.conf"
            static_dropin.parent.mkdir(parents=True)
            static_bytes = b"[Slice]\nCPUWeight=25\n"
            static_dropin.write_bytes(static_bytes)
            snapshot_path, _, capture = self.snapshot(root, [static_dropin], "")
            self.assertEqual(capture.returncode, 0, capture.stderr)

            generated = control_dir / "50-AllowedCPUs.conf"
            generated.write_bytes(b"[Slice]\nAllowedCPUs=0-5\n")
            restore = self.run_helper(
                "restore",
                "--baseline",
                str(snapshot_path),
                "--current-drop-in-paths",
                f"{static_dropin} {generated}",
                "--control-dir",
                str(control_dir),
            )

            self.assertEqual(restore.returncode, 0, restore.stderr)
            self.assertFalse(generated.exists())
            self.assertEqual(static_dropin.read_bytes(), static_bytes)
            verify = self.run_helper(
                "verify",
                "--baseline",
                str(snapshot_path),
                "--drop-in-paths",
                str(static_dropin),
                "--allowed-cpus",
                "",
            )
            self.assertEqual(verify.returncode, 0, verify.stderr)

    def test_absent_dropin_baseline_removes_the_hold_created_path(self) -> None:
        """A unit with no drop-ins returns to no paths after the hold."""
        with tempfile.TemporaryDirectory(prefix="j317-perf-slice-no-paths-") as temporary:
            root = Path(temporary)
            control_dir = root / "system.control/perf.slice.d"
            control_dir.mkdir(parents=True)
            snapshot_path, _, capture = self.snapshot(root, [], "")
            self.assertEqual(capture.returncode, 0, capture.stderr)

            generated = control_dir / "50-AllowedCPUs.conf"
            generated.write_bytes(b"[Slice]\nAllowedCPUs=0-5\n")
            restore = self.run_helper(
                "restore",
                "--baseline",
                str(snapshot_path),
                "--current-drop-in-paths",
                str(generated),
                "--control-dir",
                str(control_dir),
            )

            self.assertEqual(restore.returncode, 0, restore.stderr)
            self.assertFalse(generated.exists())
            verify = self.run_helper(
                "verify",
                "--baseline",
                str(snapshot_path),
                "--drop-in-paths",
                "",
                "--allowed-cpus",
                "",
            )
            self.assertEqual(verify.returncode, 0, verify.stderr)

    def test_audit_rejects_changed_content_path_or_allowed_cpus(self) -> None:
        """A byte, path, or property mismatch fails the baseline audit."""
        with tempfile.TemporaryDirectory(prefix="j317-perf-slice-audit-") as temporary:
            root = Path(temporary)
            dropin = root / "perf.slice.d/50-AllowedCPUs.conf"
            dropin.parent.mkdir()
            dropin.write_bytes(b"[Slice]\nAllowedCPUs=1-3\n")
            snapshot_path, _, capture = self.snapshot(root, [dropin], "1-3")
            self.assertEqual(capture.returncode, 0, capture.stderr)

            dropin.write_bytes(b"[Slice]\nAllowedCPUs=0-5\n")
            verify = self.run_helper(
                "verify",
                "--baseline",
                str(snapshot_path),
                "--drop-in-paths",
                str(dropin),
                "--allowed-cpus",
                "0-5",
            )

            self.assertEqual(verify.returncode, 2, verify.stdout)
            self.assertIn("content differs", verify.stderr)
            self.assertIn("AllowedCPUs differs", verify.stderr)


if __name__ == "__main__":
    unittest.main()
